"""REPORT.md from results/ only: every number in it is read from a file there (spec "Rules")."""
import csv, json

import numpy as np

HEAD = ("CR3-headline", "lam_F")
TABLE_METHODS = [("CR3-headline", "lam_F", "CR3, λ_F"), ("CR3-headline", "lam_V", "CR3, λ_V"),
                 ("CR3-headline", "lam_E", "CR3, λ_E"), ("CR3-headline", "lam_pool", "CR3, λ_pool"),
                 ("CR3-delta", "lam_F", "CR3 delta only, λ_F"), ("CR3-committee", "lam_F", "CR3 committee only, λ_F"),
                 ("B3-headline", "lam_1", "B3: CR3, λ = 1"), ("B1-headline", "q_b1", "B1: posterior × q̂"),
                 ("B2-committee", "lam_1", "B2: POPS (auto ridge)"), ("B2blr-committee", "lam_1", "B2: POPS (ridge blr)"),
                 ("B2lev50-committee", "lam_1", "B2 variant: POPS, leverage pct 50"),
                 ("B2blrlev50-committee", "lam_1", "B2 variant: POPS, ridge blr, leverage pct 50"),
                 ("CR3ell3-delta", "lam_F", "sensitivity: CR3 3 r_cut clusters, delta, own λ_F")]


def _read(path):
    def num(v):
        try:
            return float(v)
        except (TypeError, ValueError):
            return v
    return [{k: num(v) for k, v in r.items()} for r in csv.DictReader(open(path))]


def _f(x, d=2):
    return "–" if x in ("", None) or (isinstance(x, float) and np.isnan(x)) else f"{x:.{d}f}"


def write_report(results, out):
    cov = _read(results / "coverage.csv")
    sd = _read(results / "scale_diagnostics.csv")
    dvc = _read(results / "delta_vs_committee.csv")
    qoi = _read(results / "qoi_uq.csv")
    joint = json.load(open(results / "joint_tests.json"))
    meta = json.load(open(results / "run_metadata.json"))
    models = [m for m in ("o4d20", "o3d12") if any(r["model"] == m for r in cov)]
    get = lambda m, meth, sc: next((r for r in cov if r["model"] == m and r["method"] == meth and r["scale"] == sc), None)
    L = ["# Silicon QoI uncertainty: calibrated linear-ACE parameter UQ against DFT", ""]
    L.append(f"Generated by `python -m bench.si_qoi_uq.run --all` from `results/` (git {meta['git'][:10]}"
             f"{', dirty tree' if meta['dirty'] else ''}). Spec: `docs/dev/specs/2026-10-31-silicon-qoi-uq-propagation.md`;"
             " scope decisions: `RECON.md`.")
    L.append("")
    heads = []
    for m in models:
        h = get(m, *HEAD)
        if h:
            heads.append(f"{m}: {int(h['k95'])}/{int(h['n'])} at 95 % (CI {_f(h['ci95_lo'])}–{_f(h['ci95_hi'])}) and "
                         f"{int(h['k68'])}/{int(h['n'])} at 68 %")
    L.append("**Headline.** With the CR3 shape scaled by the force-calibrated λ_F (test-split forces only), the "
             "intervals cover the DFT value for " + "; ".join(heads) + " of the coverage QoIs (`coverage.csv`, "
             "method CR3-headline, scale lam_F).")
    L += ["", "**Calibrated on:** the 248-configuration test split's energies, forces and virials (λ_E, λ_F, λ_V, "
          "λ_pool; B1's q̂). The fits saw only the 2227 training configurations. **Not calibrated on:** any QoI or "
          "DFT QoI value. The QoIs are the validation. The optional section 7 diagnostic was not run.", ""]

    L += ["## Scale diagnostics (test split, CR3 shape; `scale_diagnostics.csv`)", "",
          "| model | λ_E | λ_F | λ_V | λ_pool | λ_V/λ_F | λ_E/λ_F | 95 % \\|z\\| F |", "|---|---|---|---|---|---|---|---|"]
    flags = []
    for m in models:
        g = {r["kind"]: r for r in sd if r["model"] == m and r["factor"] == "cr3" and r["breakdown"] == "all"}
        rv, re = g["V"]["rms_z"] / g["F"]["rms_z"], g["E"]["rms_z"] / g["F"]["rms_z"]
        L.append(f"| {m} | {_f(g['E']['rms_z'])} | {_f(g['F']['rms_z'])} | {_f(g['V']['rms_z'])} | "
                 f"{_f(g['pool']['rms_z'])} | {_f(rv)} | {_f(re)} | {_f(g['F']['q95'])} |")
        for nm, r in (("λ_V/λ_F", rv), ("λ_E/λ_F", re)):
            if not 0.8 <= r <= 1.25:
                flags.append(f"**{m}: {nm} = {_f(r)} lies outside [0.8, 1.25]**: the misspecification depends on "
                             "the observable.")
    L += ["", "λ = RMS of z = (y − ŷ)/‖Lᵀb‖ with L = D⁻¹R the CR3 factor. Rows that vanish by site symmetry are "
          "dropped (σ below 10⁻³ × the median σ of their kind)."]
    L += [""] + [f"- {f}" for f in flags] + [""]

    L += ["## Coverage of DFT and sharpness (`coverage.csv`)", "",
          "| model | method | n | 68 %: k [95 % CI] | 95 %: k [95 % CI] | RMS z | median σ/tol |",
          "|---|---|---|---|---|---|---|"]
    for m in models:
        for meth, sc, lab in TABLE_METHODS:
            r = get(m, meth, sc)
            if r:
                L.append(f"| {m} | {lab} | {int(r['n'])} | {int(r['k68'])} [{_f(r['ci68_lo'])}, {_f(r['ci68_hi'])}] | "
                         f"{int(r['k95'])} [{_f(r['ci95_lo'])}, {_f(r['ci95_hi'])}] | {_f(r['rms_z'])} | "
                         f"{_f(r['median_sigma_over_tol'])} |")
    L += ["", "n counts the coverage QoIs with a σ. That is 20, because the phonon RMS has no DFT value (RECON Q2). The delta-only rows also lack "
          "γ_us, and any phase whose E(V) argmin is not the V0 point. Intervals are Q̂ ± 1σ and ± 1.96σ. "
          "Headline σ: delta where it agrees with the λ = 1 committee to 10 %, else the committee (§4c).", ""]

    L += ["## Joint test (`joint_tests.json`, correlation-scaled, ε = 10⁻³)", "",
          "| model | method | covariance | n | df | Mahalanobis | χ²₉₅(df) | p |", "|---|---|---|---|---|---|---|---|"]
    for m in models:
        for name, r in joint.get(m, {}).items():
            for kind, jt in r.items():
                s = jt["scaled"]
                e = s["eps_0.001"]
                L.append(f"| {m} | {name} | {kind} | {s['n']} | {s['df']} | {_f(e['mahalanobis'], 1)} | "
                         f"{_f(e['chi2_95'], 1)} | {e['p_value']:.2g} |")
    L += ["", "The ε sensitivity (10⁻⁴, 10⁻²) and the absolute-units form are in `joint_tests.json`.", ""]

    L += ["## Delta method against committee (`delta_vs_committee.csv`, λ = 1)", ""]
    fl = [r for r in dvc if r.get("flagged") in ("True", True)]
    L.append(f"{len(fl)} of {sum(1 for r in dvc if r.get('flagged') in ('True', 'False', True, False))} comparisons "
             "differ by more than 10 % (the headline uses the committee σ there):")
    L.append("")
    L += ["| model | QoI | σ delta | σ committee | ratio | robust σ committee | delta / robust |", "|---|---|---|---|---|---|---|"]
    for r in fl:
        L.append(f"| {r['model']} | {r['qoi']} | {r['sigma_delta_lam1']:.3g} | {r['sigma_committee_lam1']:.3g} | "
                 f"{_f(r['ratio'])} | {_f(r.get('sigma_committee_robust_lam1'), 3)} | {_f(r.get('ratio_delta_vs_robust'))} |")
    L += ["", "Robust σ is half the 16–84 % range. Where delta/robust ≈ 1, the disagreement comes from a tail of "
          "members that change basin. It is not curvature in the bulk of the committee.", ""]

    L += ["## Elastic constants: stress and energy routes (CR3, λ_F; `qoi_uq.csv`)", "",
          "| model | QoI | Q̂ | DFT | σ stress route | σ energy route |", "|---|---|---|---|---|---|"]
    for m in models:
        for k in ("diamond_c11", "diamond_c12", "diamond_c44"):
            a = next((r for r in qoi if r["model"] == m and r["qoi"] == k and r["method"] == "CR3-delta" and r["scale"] == "lam_F"), None)
            b = next((r for r in qoi if r["model"] == m and r["qoi"] == k and r["method"] == "CR3-delta-energy-route"
                      and r["scale"] == "lam_F"), None)
            if a and b:
                L.append(f"| {m} | {k} | {_f(a['mean'], 1)} | {_f(a['dft'], 1)} | {_f(a['sigma'])} | {_f(b['sigma'])} |")
    L += ["", "The full 3×3 covariances are drawn in Fig. 4.", ""]

    L += ["## Figures", ""] + [f"![{t}](figures/{f}.png)" for f, t in (
        ("fig1_z_strip", "z per QoI"), ("fig2_coverage", "coverage"), ("fig3_qoi_correlation", "QoI correlation"),
        ("fig4_elastic_ellipses", "elastic covariance"), ("fig5_scale_diagnostics", "scale diagnostics"))] + [""]

    L += ["## Flagged issues", ""]
    for m in models:
        bad = [r for r in dvc if r["model"] == m and r.get("n_lamF_beyond_10_robust_sigma") not in ("", None)
               and r["n_lamF_beyond_10_robust_sigma"] > 0]
        if bad:
            worst = max(bad, key=lambda r: r["n_lamF_beyond_10_robust_sigma"])
            L.append(f"- {m}: the full re-run at λ_F has members beyond 10 robust σ for {len(bad)} QoIs (most: "
                     f"{int(worst['n_lamF_beyond_10_robust_sigma'])} of {int(worst['K_ok_lamF'])} for {worst['qoi']}). "
                     "They are unphysical relaxations. The SD-rescaled committee is therefore a linearisation, while its "
                     "robust spread agrees with the full re-run (`ratio_lamF_full_vs_rescaled_robust`).")
        miss = [r for r in dvc if r["model"] == m and r.get("K_ok") not in ("", None) and r["K_ok"] < 200]
        if miss:
            L.append(f"- {m}: QoIs with fewer than 200 finished λ = 1 committee runs: " +
                     ", ".join(f"{r['qoi']} ({int(r['K_ok'])})" for r in miss) + ".")
    pf = results / "pops_committee_finished.csv"
    if pf.exists():
        pr = _read(pf)
        for m in models:
            for st in sorted({r["set"] for r in pr if r["model"] == m}):
                rr = [r for r in pr if r["model"] == m and r["set"] == st and r["qoi"] != "phonon_f rms vs DFT (THz)"]
                ok = sum(r["K_finished"] >= 50 for r in rr)
                L.append(f"- {m}, POPS set `{st}`: {ok} of {len(rr)} coverage QoIs have >= 50 of 200 members finished "
                         f"(median finished per QoI {int(np.median([r['K_finished'] for r in rr]))}); a QoI below 50 "
                         "gets no σ (`pops_committee_finished.csv`).")
    ph = [r for r in qoi if r["qoi"].startswith("phonon") and r["method"] == "CR3-committee" and r["scale"] == "lam_F"]
    for r in ph:
        L.append(f"- {r['model']}: phonon RMS is excluded from coverage. The model's RMS against DFT is {_f(r['mean'], 3)} THz; "
                 f"its CR3 λ_F committee spread is {_f(r['sigma'], 3)} THz.")
    L.append("- See `RECON.md` for the fixed decisions: no QoI is linear in θ; whole-configuration CR3 clusters; "
             "sequential ARD with shared noise; ARD precisions ended at their lower bound; POPS auto ridge 1e-14 "
             "and the QR-statistics NaN, which motivated the extra ridge-blr member set.")
    out.write_text("\n".join(L) + "\n")
